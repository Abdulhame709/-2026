import assert from 'node:assert/strict';
import { createHash, randomBytes } from 'node:crypto';
import { mkdir, mkdtemp, readFile, readdir, rm, unlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import pg from 'pg';
import { BackupService } from '../dist/application/backup.service.js';
import { backupKey, decryptBackup, encryptBackup } from '../dist/application/backup-crypto.js';

const databaseName = `reconciliation_restore_test_${randomBytes(6).toString('hex')}`;
const testDir = await mkdtemp(join(tmpdir(), 'reconciliation-restore-test-'));
const backupDir = join(testDir, 'backups');
const uploadDir = join(testDir, 'uploads');
const connection = { host: '127.0.0.1', port: 5432, user: 'postgres', password: process.env.PGPASSWORD };
const admin = new pg.Client({ ...connection, database: 'postgres' });
const previousKey = process.env.BACKUP_ENCRYPTION_KEY;
let pool;
let created = false;

try {
  if (!process.env.PGPASSWORD) throw new Error('اضبط PGPASSWORD محلياً قبل الاختبار؛ لا تستخدم قاعدة العمل');
  await admin.connect();
  await admin.query(`CREATE DATABASE "${databaseName}"`);
  created = true;
  pool = new pg.Pool({ ...connection, database: databaseName });
  const migrations = join(process.cwd(), 'src', 'infrastructure', 'db', 'migrations');
  for (const name of (await readdir(migrations)).filter((file) => file.endsWith('.sql')).sort()) {
    await pool.query((await readFile(join(migrations, name))).toString('utf8'));
  }
  await mkdir(uploadDir);
  process.env.BACKUP_ENCRYPTION_KEY = randomBytes(32).toString('hex');
  const service = new BackupService(pool, { write: async () => {} }, backupDir, uploadDir);
  await pool.query('INSERT INTO settings (key, value) VALUES ($1, $2::jsonb)', ['restore_probe', JSON.stringify({ state: 1 })]);
  const logoName = 'logo-123.png';
  const originalLogo = Buffer.from('synthetic-logo');
  await writeFile(join(uploadDir, logoName), originalLogo);
  await pool.query('INSERT INTO settings (key, value) VALUES ($1, $2::jsonb)', ['company', JSON.stringify({ logoFileName: logoName })]);
  await pool.query('INSERT INTO users (username, password_hash, full_name, role, is_active) VALUES ($1,$2,$3,$4,false)', ['backup_test', 'synthetic-only', 'Synthetic Test', 'admin']);
  const sourceName = 'synthetic-invoice.pdf';
  const originalSource = Buffer.from('sensitive synthetic invoice');
  const sourcePath = join(uploadDir, sourceName);
  await writeFile(sourcePath, originalSource);
  await pool.query(
    'INSERT INTO source_files (original_name, stored_path, sha256, uploaded_by) SELECT $1,$2,$3,id FROM users WHERE username=$4',
    [sourceName, sourcePath, createHash('sha256').update(originalSource).digest('hex'), 'backup_test'],
  );
  await pool.query("INSERT INTO auth_sessions (user_id, expires_at) SELECT id, now() + interval '1 day' FROM users WHERE username = 'backup_test'");
  const actor = { id: 1, username: 'backup_test' };
  const backup = await service.create(actor, null);
  assert.ok(backup.encrypted && backup.name.endsWith('.enc'));
  const file = join(backupDir, backup.name);
  const data = await readFile(file);
  assert.ok(!data.includes(Buffer.from('restore_probe')));
  assert.ok(!data.includes(originalSource));
  assert.equal(backup.includesUploads, true);
  assert.equal(backup.fileCount, 2);
  const legacyName = 'backup-synthetic-legacy.json';
  const legacyManifest = JSON.parse(decryptBackup(data, backup.name, backupKey()).toString('utf8'));
  legacyManifest.version = 1;
  delete legacyManifest.files;
  await writeFile(join(backupDir, legacyName), Buffer.from(JSON.stringify(legacyManifest)));
  const converted = await service.encryptLegacy(legacyName, actor, null);
  assert.ok(converted.encrypted);
  assert.equal(converted.includesUploads, false);
  await service.restore(converted.name, actor, null);
  assert.equal((await pool.query('SELECT stored_path FROM source_files')).rows[0].stored_path, sourcePath);
  await pool.query('UPDATE settings SET value=$1::jsonb WHERE key=$2', [JSON.stringify({ state: 2 }), 'restore_probe']);
  const bad = Buffer.from(data);
  bad[bad.length - 1] ^= 1;
  await writeFile(file, bad);
  await assert.rejects(service.restore(backup.name, actor, null), { code: 'VALIDATION_FAILED' });
  const unreadable = (await service.list()).find((item) => item.name === backup.name);
  assert.equal(unreadable.readable, false);
  const before = await pool.query("SELECT value FROM settings WHERE key='restore_probe'");
  assert.equal(before.rows[0].value.state, 2);
  await writeFile(file, data);
  const invalidName = 'backup-synthetic-invalid.enc';
  const incomplete = JSON.parse(decryptBackup(data, backup.name, backupKey()).toString('utf8'));
  delete incomplete.tables.users;
  await writeFile(join(backupDir, invalidName), encryptBackup(Buffer.from(JSON.stringify(incomplete)), invalidName, backupKey()));
  await assert.rejects(service.restore(invalidName, actor, null), { code: 'VALIDATION_FAILED' });
  assert.equal((await pool.query("SELECT value FROM settings WHERE key='restore_probe'")).rows[0].value.state, 2);
  assert.equal((await service.list()).find((item) => item.name === invalidName).readable, false);
  const badFileName = 'backup-synthetic-bad-file.enc';
  const badFile = JSON.parse(decryptBackup(data, backup.name, backupKey()).toString('utf8'));
  badFile.files[0].data = Buffer.from('changed').toString('base64');
  await writeFile(join(backupDir, badFileName), encryptBackup(Buffer.from(JSON.stringify(badFile)), badFileName, backupKey()));
  await assert.rejects(service.restore(badFileName, actor, null), { code: 'VALIDATION_FAILED' });
  const traversalName = 'backup-synthetic-traversal.enc';
  const traversal = JSON.parse(decryptBackup(data, backup.name, backupKey()).toString('utf8'));
  traversal.files[0].name = '../escape';
  await writeFile(join(backupDir, traversalName), encryptBackup(Buffer.from(JSON.stringify(traversal)), traversalName, backupKey()));
  await assert.rejects(service.restore(traversalName, actor, null), { code: 'VALIDATION_FAILED' });
  assert.equal((await pool.query("SELECT value FROM settings WHERE key='restore_probe'")).rows[0].value.state, 2);
  await writeFile(sourcePath, Buffer.from('changed after backup'));
  await writeFile(join(uploadDir, logoName), Buffer.from('changed logo'));
  await assert.rejects(service.create(actor, null), { code: 'VALIDATION_FAILED' });
  await unlink(join(uploadDir, logoName));
  await assert.rejects(service.create(actor, null), { code: 'VALIDATION_FAILED' });
  const restored = await service.restore(backup.name, actor, null);
  assert.equal(restored.counts.settings, 2);
  const after = await pool.query("SELECT value FROM settings WHERE key='restore_probe'");
  assert.equal(after.rows[0].value.state, 1);
  const restoredSource = (await pool.query('SELECT stored_path FROM source_files')).rows[0].stored_path;
  assert.notEqual(restoredSource, sourcePath);
  assert.ok((await readFile(restoredSource)).equals(originalSource));
  const restoredLogo = (await pool.query("SELECT value FROM settings WHERE key='company'")).rows[0].value.logoFileName;
  assert.match(restoredLogo, /^logo-\d+\.png$/);
  assert.notEqual(restoredLogo, logoName);
  assert.ok((await readFile(join(uploadDir, restoredLogo))).equals(originalLogo));
  assert.equal((await readFile(sourcePath)).toString(), 'changed after backup');
  const sessions = await pool.query('SELECT count(*)::int AS total FROM auth_sessions');
  assert.equal(sessions.rows[0].total, 0);
  const audit = await pool.query("SELECT actor_id, after FROM audit_log WHERE action='BACKUP_RESTORE'");
  assert.equal(Number(audit.rows[0].actor_id), actor.id);
  assert.equal(audit.rows[0].after.requestedBy, actor.username);
  await service.restore(backup.name, { id: actor.id, username: 'former_admin' }, null);
  const replacedActor = await pool.query("SELECT actor_id, after FROM audit_log WHERE action='BACKUP_RESTORE' ORDER BY id DESC LIMIT 1");
  assert.equal(replacedActor.rows[0].actor_id, null);
  assert.equal(replacedActor.rows[0].after.requestedBy, 'former_admin');
  const beforeFailedRestore = (await readdir(uploadDir)).length;
  const invalidRowName = 'backup-synthetic-invalid-row.enc';
  const invalidRow = JSON.parse(decryptBackup(data, backup.name, backupKey()).toString('utf8'));
  invalidRow.tables.source_files[0].uploaded_by = 999999;
  await writeFile(join(backupDir, invalidRowName), encryptBackup(Buffer.from(JSON.stringify(invalidRow)), invalidRowName, backupKey()));
  await assert.rejects(service.restore(invalidRowName, actor, null), { code: 'VALIDATION_FAILED' });
  assert.equal((await readdir(uploadDir)).length, beforeFailedRestore);
  assert.equal((await pool.query("SELECT value FROM settings WHERE key='restore_probe'")).rows[0].value.state, 1);
  await assert.rejects(service.restore(converted.name, actor, null), { code: 'VALIDATION_FAILED' });
  assert.equal((await service.list()).length, 7);
  const transferredDir = join(testDir, 'transferred-uploads');
  const transferredService = new BackupService(pool, { write: async () => {} }, backupDir, transferredDir);
  await transferredService.restore(backup.name, actor, null);
  const transferredPath = (await pool.query('SELECT stored_path FROM source_files')).rows[0].stored_path;
  assert.equal(dirname(transferredPath), transferredDir);
  assert.ok((await readFile(transferredPath)).equals(originalSource));
  const transferredLogo = (await pool.query("SELECT value FROM settings WHERE key='company'")).rows[0].value.logoFileName;
  assert.ok((await readFile(join(transferredDir, transferredLogo))).equals(originalLogo));
  const key = process.env.BACKUP_ENCRYPTION_KEY;
  delete process.env.BACKUP_ENCRYPTION_KEY;
  await assert.rejects(service.list(), { code: 'BACKUP_KEY_REQUIRED' });
  process.env.BACKUP_ENCRYPTION_KEY = key;
  await assert.rejects(service.filePath(legacyName), { code: 'VALIDATION_FAILED' });
  console.log('PASS: isolated encrypted database/files restore, tamper and rollback checks, legacy safety and session exclusion');
} finally {
  if (previousKey === undefined) delete process.env.BACKUP_ENCRYPTION_KEY;
  else process.env.BACKUP_ENCRYPTION_KEY = previousKey;
  if (pool) await pool.end();
  if (created) await admin.query(`DROP DATABASE "${databaseName}"`);
  await admin.end().catch(() => undefined);
  if (dirname(resolve(testDir)) !== resolve(tmpdir()) || !basename(testDir).startsWith('reconciliation-restore-test-')) {
    throw new Error('رفض تنظيف مسار غير متوقع للاختبار');
  }
  await rm(testDir, { recursive: true, force: true });
}
